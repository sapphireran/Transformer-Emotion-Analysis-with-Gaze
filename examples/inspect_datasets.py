"""Inventory every checked-in table that the docs talk about.

Writes examples/output/dataset_inventory.md with row counts, columns,
label histograms, and a short numeric summary of gaze columns.
"""

from __future__ import annotations

import argparse

import pandas as pd

from common import (
    EXPECTED_ROW_COUNTS,
    INVENTORY,
    LABEL_NAMES,
    OUTPUT_DIR,
    SST_FUSION_COLUMNS,
    ZUCO_FUSION_COLUMNS,
    ensure_output_dir,
    read_csv,
    write_text,
)


GAZE_HINTS = set(ZUCO_FUSION_COLUMNS + SST_FUSION_COLUMNS + [
    "omissionRate",
    "meanPupilSize",
    "SFD",
    "SentLen",
    "WordLen",
    "fixProp",
])


def _summarize(path_key: str, path) -> dict:
    header = None if path.name == "stts_all_sentence_level.csv" else "infer"
    if header is None:
        df = read_csv(path, header=None, names=["sentence", "sentiment_name"])
    else:
        df = read_csv(path)

    info = {
        "key": path_key,
        "rows": len(df),
        "cols": list(df.columns),
        "expected_rows": EXPECTED_ROW_COUNTS.get(path_key),
        "labels": None,
        "gaze": None,
        "sent_words": None,
    }

    if "sentiment_label" in df.columns:
        info["labels"] = (
            df["sentiment_label"].value_counts().sort_index().to_dict()
        )
    elif "sentiment_name" in df.columns:
        info["labels"] = df["sentiment_name"].value_counts().to_dict()

    if "sentence" in df.columns:
        lengths = df["sentence"].astype(str).str.split().str.len()
        info["sent_words"] = {
            "mean": float(lengths.mean()),
            "min": int(lengths.min()),
            "max": int(lengths.max()),
        }

    gaze_cols = [c for c in df.columns if c in GAZE_HINTS]
    if gaze_cols:
        desc = df[gaze_cols].describe().T
        info["gaze"] = {
            col: {
                "mean": float(desc.loc[col, "mean"]),
                "std": float(desc.loc[col, "std"]),
                "min": float(desc.loc[col, "min"]),
                "max": float(desc.loc[col, "max"]),
            }
            for col in gaze_cols
        }
    return info


def _md_table(info: dict) -> str:
    lines = [f"## `{info['key']}`", ""]
    match = ""
    if info["expected_rows"] is not None:
        match = " yes" if info["rows"] == info["expected_rows"] else " **MISMATCH**"
    lines.append(f"- rows: {info['rows']} (documented {info['expected_rows']}){match}")
    lines.append(f"- columns: {', '.join(str(c) for c in info['cols'])}")
    if info["labels"] is not None:
        pretty = []
        for key, count in info["labels"].items():
            name = LABEL_NAMES.get(key, key)
            pretty.append(f"{key}={name}:{count}")
        lines.append(f"- labels: {', '.join(pretty)}")
    if info["sent_words"] is not None:
        sw = info["sent_words"]
        lines.append(
            f"- sentence length (words): mean {sw['mean']:.2f}, "
            f"min {sw['min']}, max {sw['max']}"
        )
    if info["gaze"]:
        lines.append("")
        lines.append("| feature | mean | std | min | max |")
        lines.append("| --- | ---: | ---: | ---: | ---: |")
        for col, stats in info["gaze"].items():
            lines.append(
                f"| {col} | {stats['mean']:.4f} | {stats['std']:.4f} | "
                f"{stats['min']:.4f} | {stats['max']:.4f} |"
            )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    ensure_output_dir()

    chunks = [
        "# Dataset inventory",
        "",
        "Generated by `examples/inspect_datasets.py`.",
        "",
    ]
    mismatches = []
    for key, path in INVENTORY.items():
        info = _summarize(key, path)
        chunks.append(_md_table(info))
        if info["expected_rows"] is not None and info["rows"] != info["expected_rows"]:
            mismatches.append((key, info["rows"], info["expected_rows"]))

    if mismatches:
        chunks.append("## Row-count mismatches")
        chunks.append("")
        for key, got, expected in mismatches:
            chunks.append(f"- `{key}`: got {got}, expected {expected}")
        chunks.append("")
    else:
        chunks.append("All documented row counts match this checkout.")
        chunks.append("")

    out = OUTPUT_DIR / "dataset_inventory.md"
    write_text(out, "\n".join(chunks))
    print(f"Wrote {out}")
    print(f"Tables inventoried: {len(INVENTORY)}")
    if mismatches:
        print(f"Row-count mismatches: {len(mismatches)}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
